export const defaultUiThemeId: UiThemeId = 'citrusPoster'

const uiThemes: Record<UiThemeId, UiThemeDefinition> = {
  citrusPoster,
  noirBloom,
  midnightSignal,
  magentaPulse,
  emberGlow,
  matrixTerminal,
}

export const uiThemesList = [citrusPoster, noirBloom, midnightSignal, magentaPulse, emberGlow, matrixTerminal] as const

export const getUiTheme = (id: UiThemeId | undefined): UiThemeDefinition =>
  (id ? uiThemes[id] : undefined) ?? uiThemes[defaultUiThemeId]

export const getUiThemeOverlayPalette = (id: UiThemeId | undefined) => getUiTheme(id).overlayPalette

export const applyUiTheme = (
  themeId: UiThemeId | undefined,
  root: HTMLElement = document.documentElement,
  mode: ThemeMode = root.classList.contains('dark') ? 'dark' : 'light',
) => {
  const theme = getUiTheme(themeId)
  const tokens = theme.tokens[mode]

  if (mode === 'dark') {
    root.classList.add('dark')
  } else {
    root.classList.remove('dark')
  }

  root.dataset.uiTheme = theme.id

  for (const [key, value] of Object.entries(tokens)) {
    root.style.setProperty(`--${key}`, value)
  }
}
